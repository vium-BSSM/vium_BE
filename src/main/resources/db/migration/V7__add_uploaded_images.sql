CREATE TABLE uploaded_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    purpose VARCHAR(20) NOT NULL CHECK (purpose IN ('RECEIPT', 'PROFILE', 'RECIPE')),
    bucket VARCHAR(63) NOT NULL,
    object_key VARCHAR(200) NOT NULL UNIQUE,
    content_type VARCHAR(30) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png')),
    size_bytes BIGINT NOT NULL CHECK (size_bytes BETWEEN 1 AND 5242880),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ready BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_uploaded_images_owner ON uploaded_images(user_id);
CREATE INDEX idx_uploaded_images_cleanup ON uploaded_images(ready, created_at);
COMMENT ON TABLE uploaded_images IS 'S3 이미지 메타데이터. ready=false는 업로드 중 또는 정리 재시도 대상';
